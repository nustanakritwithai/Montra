/** Compact identity: production helpers, inert labels and no protocol mutations. */
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.join(__dirname, '../..'), source = fs.readFileSync(path.join(root, 'main.js'), 'utf8'), html = fs.readFileSync(path.join(root, 'index.html'), 'utf8'), css = fs.readFileSync(path.join(root, 'styles.css'), 'utf8');
const start = source.indexOf('  function characterPowerEstimate('), end = source.indexOf('  function updateCharacterHud(', start);
assert(start > 0 && end > start);
const elements = new Map(['characterName','characterLevel','characterClass','characterPower','characterProfile'].map(id => [id, {textContent:'',setAttribute(k,v){this[k]=v;}}]));
const context = { $:id=>elements.get(id), getBuildCatalog:()=>({paths:{blade:{name:'คมดาบ'}}}), hudSet:(el,key,value)=>{el.textContent=value;} };
vm.createContext(context); vm.runInContext(source.slice(start,end), context);
const power = context.characterPowerEstimate;
assert.equal(power({atk:25,magicAtk:15,def:18,magicDef:12,maxHp:100,level:1}),195);
assert.equal(power({atk:0,magicAtk:0,def:0,magicDef:0,maxHp:0,level:0}),0);
assert.equal(power({atk:-3,magicAtk:0,def:0,magicDef:0,maxHp:0,level:1}),20);
for(const invalid of [null,{}, {atk:1,magicAtk:0,def:0,magicDef:0,maxHp:100,level:NaN}, {atk:'20',magicAtk:0,def:0,magicDef:0,maxHp:100,level:1}]) assert.equal(power(invalid),null);
context.$('characterName').textContent='<img src=x onerror=alert(1)>ชื่อยาวมาก'; context.$('characterLevel').textContent='S3 · LV. 100';
context.updateCompactCharacterHud({pathId:'blade',atk:25,magicAtk:15,def:18,magicDef:12,maxHp:100,level:100});
assert.equal(context.$('characterClass').textContent,'คมดาบ'); assert.equal(context.$('characterPower').textContent,'2,175');
assert(context.$('characterProfile')['aria-label'].includes('S3 · LV. 100'));
context.updateCompactCharacterHud(null); assert.equal(context.$('characterPower').textContent,'—');assert.equal(context.$('characterClass').textContent,'นักผจญภัย');
assert(!context.$('characterProfile')['aria-label'].includes('ประมาณ'));
assert.equal((html.match(/id="characterProfile"/g)||[]).length,1);
assert.match(html,/<button id="characterProfile"[^>]*aria-haspopup="dialog"/);
assert.match(html,/<div class="legacy-character-meters" hidden>/);
assert.deepEqual([...source.matchAll(/\$\("([^"]+)"\)\.onclick=openCharacterProfile\b/g)].map(match=>match[1]),['characterProfile']);
assert.doesNotMatch(html, /\bid="menuCharacter"/);
assert.doesNotMatch(source, /\bmenuCharacter\b/);
assert.match(html, /data-journal-tab="character"[^>]*>สกิลและคู่หู<\/button>/);
assert.match(source,/const cpVal = characterPowerEstimate\(char\)/);
assert.match(source,/updateCompactCharacterHud\(me\);/);
assert.match(css,/\.identity \.portrait.low-hp \{ border-color:#ff6a5a/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\).*\.identity \.portrait.low-hp \{ animation:none;/);
assert(!css.includes('.hud-journal .identity { display: none !important; }'));
console.log('PASS compact character HUD: shared power, zero/missing/invalid stats, safe labels, save-slot accessibility, profile action and low-HP styles');
